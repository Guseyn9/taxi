import { formatShortAddress } from './address'

describe('formatShortAddress', () => {

  it('срезает административный хвост геокодера', () => {
    expect(formatShortAddress(
      'исторический район Хуфен, улица Сержанта Колоскова, район Хуфен, Калининград, ' +
      'городской округ Калининград, Калининградская область, Северо-Западный федеральный округ, ' +
      '236022, Россия',
    )).toBe('улица Сержанта Колоскова, Калининград')

    expect(formatShortAddress(
      'Портовая улица, Московский район, Калининград, городской округ Калининград, ' +
      'Калининградская область, Северо-Западный федеральный округ, 236039, Россия',
    )).toBe('Портовая улица, Калининград')
  })

  it('оставляет номер дома при объекте или улице', () => {
    expect(formatShortAddress(
      'МОТОС-АВТО, 17, улица Дмитрия Донского, район Хуфен, Калининград, ' +
      'городской округ Калининград, Калининградская область, 236022, Россия',
    )).toBe('МОТОС-АВТО, 17, улица Дмитрия Донского')
  })

  it('обрезает слишком длинный адрес многоточием', () => {
    const short = formatShortAddress('Очень длинное название торгово-развлекательного центра, Калининград')
    expect(short.length).toBeLessThanOrEqual(48)
    expect(short.endsWith('…')).toBe(true)
  })

  it('не теряет нестандартные адреса', () => {
    expect(formatShortAddress('54.7104, 20.4522')).toBe('54.7104, 20.4522')
    expect(formatShortAddress('Калининград')).toBe('Калининград')
    expect(formatShortAddress('')).toBe('')
    expect(formatShortAddress(undefined)).toBe('')
  })

})
